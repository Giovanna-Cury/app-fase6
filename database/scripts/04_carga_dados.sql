-- Estado atual de cada sensor = ultima leitura do historico.
MERGE INTO shas_sensor s
USING (SELECT id_sensor, valor, classificacao, dt_leitura
         FROM (SELECT l.id_sensor, l.valor, l.classificacao, l.dt_leitura,
                      ROW_NUMBER() OVER (PARTITION BY l.id_sensor ORDER BY l.dt_leitura DESC) AS rn
                 FROM shas_leitura l)
        WHERE rn = 1) u
   ON (s.id_sensor = u.id_sensor)
 WHEN MATCHED THEN UPDATE SET
      s.valor_atual    = u.valor,
      s.dt_atualizacao = u.dt_leitura,
      s.status         = CASE u.classificacao WHEN 'NORMAL' THEN 'ONLINE' ELSE 'WARNING' END;

