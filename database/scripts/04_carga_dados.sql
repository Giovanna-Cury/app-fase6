           || ' ' || s.unidade || ' registrado (histórico).',
       'CRITICAL', s.localizacao, 'AUTOMATICO', s.id_sensor, l.id_leitura, 1,
       l.dt_leitura, l.dt_leitura + NUMTODSINTERVAL(45, 'MINUTE')
  FROM (SELECT x.*,
               ROW_NUMBER() OVER (PARTITION BY x.id_sensor, TRUNC(x.dt_leitura)
                                  ORDER BY x.dt_leitura) AS rn
          FROM shas_leitura x
         WHERE x.classificacao = 'CRITICA'
           AND x.dt_leitura < TRUNC(SYSDATE)) l
  JOIN shas_sensor s ON s.id_sensor = l.id_sensor
 WHERE l.rn = 1;

