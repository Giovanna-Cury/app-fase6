-- -----------------------------------------------------------------------------
-- Eventos em "tempo real": as proprias procedures geram os alertas automaticos.
-- -----------------------------------------------------------------------------
DECLARE
    v_id_leitura shas_leitura.id_leitura%TYPE;
    v_class      shas_leitura.classificacao%TYPE;
    v_id_alerta  shas_alerta.id_alerta%TYPE;
    v_qtd        NUMBER;
BEGIN
    -- AQI critico no Ibirapuera -> cria alerta CRITICAL
    prc_registrar_leitura(3, 162.40, v_id_leitura, v_class, v_id_alerta);
    DBMS_OUTPUT.PUT_LINE('Sensor 03: ' || v_class || ' / alerta ' || v_id_alerta);

    -- Nivel de agua em alerta na Marginal -> cria alerta MEDIUM ...
    prc_registrar_leitura(5, 78.50, v_id_leitura, v_class, v_id_alerta);
    DBMS_OUTPUT.PUT_LINE('Sensor 05: ' || v_class || ' / alerta ' || v_id_alerta);

    -- ... e a proxima leitura critica ESCALONA o mesmo alerta para CRITICAL
    prc_registrar_leitura(5, 91.20, v_id_leitura, v_class, v_id_alerta);
    DBMS_OUTPUT.PUT_LINE('Sensor 05: ' || v_class || ' / alerta ' || v_id_alerta || ' (escalonado)');

    COMMIT; -- procedure online: o chamador decide o commit

    -- Watchdog: sensor 04 sem comunicacao ha mais de 60 min -> OFFLINE + alerta
    prc_verificar_sensores_inativos(60, v_qtd);
    DBMS_OUTPUT.PUT_LINE('Sensores marcados OFFLINE: ' || v_qtd);

    -- Relatorios diarios dos ultimos 8 dias (hoje inclusive)
    FOR d IN 0 .. 7 LOOP
        prc_gerar_relatorio_diario(TRUNC(SYSDATE) - d, v_qtd);
    END LOOP;
    DBMS_OUTPUT.PUT_LINE('Relatorios diarios gerados.');
END;
