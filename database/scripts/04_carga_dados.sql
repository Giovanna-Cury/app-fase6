-- -----------------------------------------------------------------------------
-- Telemetria simulada: 7 dias, uma leitura a cada 30 minutos por sensor.
-- valor = base + amplitude * sen(ciclo diario) + ruido gaussiano (+ picos 2%)
-- -----------------------------------------------------------------------------
DECLARE
    c_intervalo_min CONSTANT PLS_INTEGER := 30;
    c_dias          CONSTANT PLS_INTEGER := 7;
    c_prob_pico     CONSTANT NUMBER      := 0.02;
    c_pi            CONSTANT NUMBER      := ACOS(-1);

    v_passos  PLS_INTEGER := c_dias * 24 * 60 / c_intervalo_min;
    v_agora   TIMESTAMP   := CAST(TRUNC(SYSDATE, 'HH24') AS TIMESTAMP)
                             + NUMTODSINTERVAL(FLOOR(TO_NUMBER(TO_CHAR(SYSDATE, 'MI')) / 30) * 30, 'MINUTE');
    v_base    NUMBER;
    v_amp     NUMBER;
    v_ruido   NUMBER;
    v_teto    NUMBER;
    v_dt      TIMESTAMP;
    v_hora    NUMBER;
    v_valor   NUMBER;
    v_total   PLS_INTEGER := 0;
BEGIN
    DBMS_RANDOM.SEED(2026);

    FOR s IN (SELECT id_sensor, nome, limite_alerta, limite_critico
                FROM shas_sensor
               ORDER BY id_sensor) LOOP

        -- Perfil estatistico de cada sensor
        CASE s.id_sensor
            WHEN 1 THEN v_base := 24; v_amp := 5;  v_ruido := 1.2; v_teto := NULL;
            WHEN 2 THEN v_base := 62; v_amp := 12; v_ruido := 3.0; v_teto := 100;
            WHEN 3 THEN v_base := 72; v_amp := 14; v_ruido := 6.0; v_teto := NULL;
            WHEN 4 THEN v_base := 28; v_amp := 22; v_ruido := 6.0; v_teto := NULL;
            WHEN 5 THEN v_base := 55; v_amp := 8;  v_ruido := 3.5; v_teto := 100;
            WHEN 6 THEN v_base := 63; v_amp := 9;  v_ruido := 2.5; v_teto := NULL;
            WHEN 7 THEN v_base := 26; v_amp := 5;  v_ruido := 1.2; v_teto := NULL;
            ELSE        v_base := 48; v_amp := 10; v_ruido := 4.5; v_teto := 100;
        END CASE;

        FOR i IN REVERSE 0 .. v_passos - 1 LOOP
            -- Sensor 04 parou de comunicar ha ~3h: demonstra o watchdog PL/SQL.
            CONTINUE WHEN s.id_sensor = 4 AND i < 6;

            v_dt    := v_agora - NUMTODSINTERVAL(i * c_intervalo_min, 'MINUTE');
            v_hora  := EXTRACT(HOUR FROM v_dt) + EXTRACT(MINUTE FROM v_dt) / 60;
            v_valor := v_base
                       + v_amp * SIN(2 * c_pi * (v_hora - 9) / 24)   -- pico as 15h
                       + DBMS_RANDOM.NORMAL * v_ruido;

            IF DBMS_RANDOM.VALUE < c_prob_pico THEN
                v_valor := s.limite_critico + DBMS_RANDOM.VALUE(0, v_amp);  -- evento critico
            END IF;

            v_valor := ROUND(GREATEST(0, v_valor), 2);
            IF v_teto IS NOT NULL THEN
                v_valor := LEAST(v_teto, v_valor);
            END IF;

            INSERT INTO shas_leitura (id_sensor, valor, classificacao, dt_leitura)
            VALUES (s.id_sensor, v_valor,
                    fn_classificar_leitura(v_valor, s.limite_alerta, s.limite_critico), v_dt);
            v_total := v_total + 1;
        END LOOP;
    END LOOP;

    DBMS_OUTPUT.PUT_LINE('Leituras simuladas inseridas: ' || v_total);
END;
